-- Supabase SQL Editor: run this once to create the readings table.
create table if not exists public.readings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  co2 double precision not null check (co2 >= 0 and co2 < 10000),
  temperature double precision not null check (temperature > -50 and temperature < 100),
  humidity double precision not null check (humidity >= 0 and humidity <= 100),
  reactor_on boolean not null default false
);

alter table public.readings enable row level security;

-- EDUCATIONAL PROTOTYPE ONLY:
-- These policies allow anyone with the public anon key to read and insert.
-- For a public production site, use authenticated users or a server-side
-- Edge Function with a secret; never expose service_role keys in browser/ESP32.
create policy "public can read project readings"
on public.readings for select
to anon, authenticated
using (true);

create policy "device can insert project readings"
on public.readings for insert
to anon, authenticated
with check (true);

grant select, insert on public.readings to anon, authenticated;
grant usage, select on sequence public.readings_id_seq to anon, authenticated;
